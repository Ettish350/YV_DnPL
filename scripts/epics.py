# -*- coding: utf-8 -*-
import openpyxl
from openpyxl.styles import Font, PatternFill, Alignment, Border, Side
from openpyxl.utils import get_column_letter

F = "Arial"
ACC = "1F3864"
HDR = PatternFill("solid", fgColor="DDEBF7")
L0F = PatternFill("solid", fgColor="FFF2CC")
PILOT = PatternFill("solid", fgColor="E2EFDA")
thin = Side(style="thin", color="BFBFBF")
BOX = Border(left=thin, right=thin, top=thin, bottom=thin)

wb = openpyxl.Workbook()


def sheet(title, headers, widths, rows, freeze="A2", note=None):
    ws = wb.create_sheet(title)
    ws.sheet_view.rightToLeft = True
    r = 1
    if note:
        ws.cell(1, 1, note)
        c = ws.cell(1, 1)
        c.font = Font(name=F, size=10, italic=True, color="555555")
        ws.merge_cells(start_row=1, start_column=1, end_row=1, end_column=len(headers))
        r = 2
    hr = r
    for i, h in enumerate(headers, 1):
        c = ws.cell(hr, i, h)
        c.font = Font(name=F, size=10, bold=True, color=ACC)
        c.fill = HDR
        c.border = BOX
        c.alignment = Alignment(wrap_text=True, vertical="center", horizontal="right")
    for j, row in enumerate(rows):
        for i, v in enumerate(row, 1):
            c = ws.cell(hr + 1 + j, i, v)
            c.font = Font(name=F, size=10)
            c.border = BOX
            c.alignment = Alignment(wrap_text=True, vertical="top", horizontal="right")
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = ws.cell(hr + 1, 1)
    return ws, hr


