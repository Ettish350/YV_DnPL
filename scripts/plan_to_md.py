# -*- coding: utf-8 -*-
"""Write a read-only Markdown copy of the plan workbook (D-032).

Usage (from the repo root):
    python3 scripts/plan_to_md.py "plan/workbooks/<approved workbook version>.xlsx"

The plan workbook is edited on SharePoint (`06 תכנון וספרינטים`). Each approved version is committed to
plan/workbooks/ (it holds no personal information, D-031), and this script is run on it. It writes:
    plan/implementation-plan.md          the first tab (the whole plan, all sprints)
    plan/sprints/<YYYY-MM-DD>.md         one file per sprint tab, named by the sprint start date
Cell text stays in Hebrew, as in the workbook. Do not edit the output by hand: change the workbook, then rerun.
Lior's or Anna's Claude runs it after each approved workbook version.
"""
import datetime, hashlib, os, re, sys
import openpyxl

# Hebrew workbook header -> English column name. Columns not listed here (for example the editable team list) are left out.
COLS = {"אפוס": "Epic", "משימה": "Task", "התחלה": "Start", "סיום": "End", "מיישם": "Implementer", "בודק": "Reviewer",
        "אובייקטים ושדות": "Objects and fields", "מסכים, פריסות ודוחות": "Screens, layouts, reports",
        "כללי תקינות": "Validation rules", "אוטומציות": "Automations", "הרשאות": "Permissions",
        "תבניות, נתונים ואחר": "Templates, data, other", "בדיקת יחידה": "Unit test", 'סה"כ שעות': "Total h",
        "אחוז ביצוע": "% done", "שעות שנותרו": "Hours left", "מקור באפיון": "DD source", "הערה": "Note",
        "מצב בסביבה": "Sandbox state", "רכיבים שנמצאו בסביבה": "Components found in sandbox",
        "ישות מקור וקישורים": "Source entity and lookups", "אושר לפתיחה ב-Jira": "Approved for Jira",
        "מפתח ב-Jira": "Jira key",
        # sprint tab layout from V16 (22.10.2026): one research task per legacy entity, one build task per object
        "ישות במערכת הישנה": "Legacy entity", "אובייקט בסיילספורס": "Salesforce object", "מה הישות עושה": "What it does",
        "מקור באפיון ומה הוא אומר": "DD source and what it says", "מה לעשות": "Steps"}
HEADER_ROW = 4


def cell(v):
    if v is None:
        return ""
    if isinstance(v, (datetime.datetime, datetime.date)):
        return v.strftime("%d.%m.%Y")
    if isinstance(v, float):
        return f"{v:g}" if v != int(v) or abs(v) >= 1 else f"{v:g}"
    return str(v).replace("|", "/").replace("\n", " ").strip()


def pct(v):
    return "" if v is None else f"{round(float(v) * 100)}%"


def is_task(r):
    """A task row has both an epic (hidden object column from V16) and a task. A row with a task but no epic is an
    object separator row (from V17, 22.10.2026): its hours sum the tasks below it, so it is not a task."""
    return bool(r.get("Task")) and bool(r.get("Epic"))


def rows_of(ws):
    """Return (column names, rows as dicts) for the known columns, skipping rows with no epic and no task."""
    idx = [(i, COLS[str(c.value).strip()]) for i, c in enumerate(ws[HEADER_ROW]) if c.value and str(c.value).strip() in COLS]
    names = [n for _, n in idx]
    out = []
    for r in ws.iter_rows(min_row=HEADER_ROW + 1, values_only=True):
        d = {n: (r[i] if i < len(r) else None) for i, n in idx}
        if d.get("Epic") is None and d.get("Task") is None:
            continue
        out.append(d)
    return names, out


def table(names, rows):
    lines = ["| " + " | ".join(names) + " |", "|" + "---|" * len(names)]
    for r in rows:
        vals = []
        for n in names:
            v = r.get(n)
            if n == "% done":
                vals.append(pct(v))
            elif n == "Hours left" and isinstance(v, float):
                vals.append(f"{v:.1f}".rstrip("0").rstrip("."))
            else:
                vals.append(cell(v))
        if not is_task(r):  # epic summary, object separator or total row
            vals = [f"**{x}**" if x else "" for x in vals]
        lines.append("| " + " | ".join(vals) + " |")
    return "\n".join(lines)


def sprint_start(title, intro):
    m = re.search(r"(\d{1,2})\.(\d{1,2})\s*עד\s*(\d{1,2})\.(\d{1,2})(?:\.(\d{4}))?", title + " " + intro)
    if not m:
        return None
    year = int(m.group(5) or re.search(r"(20\d\d)", intro).group(1))
    return datetime.date(year, int(m.group(2)), int(m.group(1)))


def main(path):
    name = os.path.basename(path)
    sha = hashlib.sha256(open(path, "rb").read()).hexdigest()[:12]
    wb = openpyxl.load_workbook(path, data_only=True)
    stamp = (f"Generated by `scripts/plan_to_md.py` from `{name}` (SHA-256 {sha}...). "
             "Read-only copy of the approved workbook in `plan/workbooks/` (D-028, D-032). "
             "Do not edit by hand; change the workbook and rerun.")
    os.makedirs("plan/sprints", exist_ok=True)
    written = []
    for i, ws in enumerate(wb.worksheets):
        title = cell(ws.cell(1, 1).value)
        intro = cell(ws.cell(2, 1).value)
        names, rows = rows_of(ws)
        if i == 0:
            out = "plan/implementation-plan.md"
            heading = "# Implementation plan, Docs 1 and 2"
        else:
            start = sprint_start(ws.title, title + " " + intro)
            if not start:
                print(f"skipped tab {ws.title!r}: no sprint dates in its name")
                continue
            out = f"plan/sprints/{start.isoformat()}.md"
            heading = f"# Sprint {start.strftime('%d.%m.%Y')}: {title}"
        tasks = [r for r in rows if is_task(r)]
        num = lambda v: float(v) if isinstance(v, (int, float)) else 0.0
        total = sum(num(r.get("Total h")) for r in tasks)
        left = sum(num(r.get("Hours left")) for r in tasks)
        people = {}
        for r in tasks:
            p = cell(r.get("Implementer")) or "(not assigned)"
            a = people.setdefault(p, [0, 0.0, 0.0])
            a[0] += 1; a[1] += num(r.get("Total h")); a[2] += num(r.get("Hours left"))
        summary = ["| Implementer | Tasks | Hours | Hours left (workbook) |", "|---|---|---|---|"]
        summary += [f"| {p} | {a[0]} | {a[1]:g} | {a[2]:.1f} |" for p, a in people.items()]
        body = [heading, "", stamp, "", f"Workbook tab: `{ws.title}`.", "", "## Intro (from the workbook)", "", intro, "",
                f"## Totals", "", f"{len(tasks)} tasks, {total:g} hours, {left:.1f} hours left by the workbook's own estimate.", "",
                "\n".join(summary), "", "## Tasks", "",
                "Epic summary and object separator rows are in bold. Hours by category, then total, percent done and hours left as the workbook computes them.", "",
                table(names, rows), ""]
        open(out, "w", encoding="utf-8").write("\n".join(body))
        written.append(out)
    for w in written:
        print("wrote", w)


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
